# Task 1 - Check number is even or odd
num = int(input('Enter a number?'))
print(num,"is an even number") if num % 2 == 0 else print(num,"is an odd number")

# Task 2 - Sum of integers using for from 1 to 50
summation = 0
for i in range(1,51):
    summation = summation + i
print("The sum of numbers from 1 to 50 is", summation)

